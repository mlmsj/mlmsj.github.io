export const getCategoryFolderEntries = (
  categoryId: string | null | undefined,
): readonly CategoryFolderEntry[] =>
  categoryId
    ? CATEGORY_FOLDER_PILOT.filter((entry) => entry.categoryId === categoryId)
    : [];

export const getCategoryFolderItemCount = (
  categoryId: string | null | undefined,
): number =>
  getCategoryFolderEntries(categoryId).reduce(
    (total, entry) => total + entry.itemCount,
    0,
  );

export const getCategoryContentItemCount = (
  categoryId: string | null | undefined,
): number | undefined => {
  if (!categoryId) return undefined;
  const summary = CATEGORY_CONTENT_SUMMARIES.find(
    (item) => item.categoryId === categoryId,
  );
  if (summary) return summary.itemCount;
  const folderCount = getCategoryFolderItemCount(categoryId);
  if (folderCount > 0) return folderCount;
  return undefined;
};

/**
 * Lightweight public-entry projection for audited Quark child folders. These
 * entries stay outside the public manifest and recent-update feed, while the
 * library can search, list, and count every directly accessible folder once.
 */
export const CATEGORY_FOLDER_SEARCH_RESOURCES: readonly Resource[] =
  CATEGORY_FOLDER_PILOT.map((entry) => {
    const keywords = Array.from(
      new Set(
        [
          ...(entry.keywords ?? []),
          entry.sourceName,
          entry.groupLabel,
        ].filter((value): value is string => Boolean(value && value.trim())),
      ),
    );

    return {
      id: `category-folder:${entry.id}`,
      title: entry.title,
      meta: "夸克网盘 · 文件夹",
      tag: entry.groupLabel ?? "下级资料",
      description: entry.description,
      keywords,
      categoryId: entry.categoryId,
      classificationStatus: "classified",
      publicationStatus: "published",
      isPubliclyAccessible: true,
      fileType: "folder",
      delivery: {
        provider: "quark",
        shareUrl: entry.shareUrl,
        accessStatus: "verified",
        checkedOn: null,
      },
    } satisfies Resource;
  });

/**
 * Add audited child-folder entries to the public resource entries without
 * counting the same resource ID or direct share target twice.
 */
export const mergeAccessibleResourceEntries = (
  resourceValues: readonly Resource[],
  folderResourceValues: readonly Resource[] = CATEGORY_FOLDER_SEARCH_RESOURCES,
): Resource[] => {
  const merged: Resource[] = [];
  const resourceIds = new Set<string>();
  const shareTargets = new Set<string>();
  const append = (resource: Resource, deduplicateShareTarget: boolean) => {
    const shareUrl = resource.delivery?.shareUrl;
    const shareTarget = shareUrl
      ? `${resource.delivery?.provider ?? "unknown"}:${shareUrl}`
      : null;
    if (
      resourceIds.has(resource.id) ||
      (deduplicateShareTarget &&
        shareTarget !== null &&
        shareTargets.has(shareTarget))
    ) {
      return;
    }
    resourceIds.add(resource.id);
    if (shareTarget !== null) shareTargets.add(shareTarget);
    merged.push(resource);
  };

  resourceValues.forEach((resource) => append(resource, false));
  folderResourceValues.forEach((resource) => append(resource, true));
  return merged;
};

export const isCategoryFolderSearchResource = (resource: Pick<Resource, "id">) =>
  resource.id.startsWith("category-folder:");
